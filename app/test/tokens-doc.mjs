// The token reference in docs/rebuild/design-system.md is generated from the shipped tokens (app/src/v2/css/tokens.css), so the
// "one source" can't fall behind the CSS again (design audit Nov 16, P1 item 1: the doc had the old Dusk values and missed ~150
// tokens). Every token with its day and night value, grouped by family; solid colours get their contrast on the page background.
//   node app/test/tokens-doc.mjs           check: exit 1 if the doc's reference is out of date
//   node app/test/tokens-doc.mjs --write   rewrite the reference between the markers
import fs from 'node:fs'; import {fileURLToPath} from 'node:url';
const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const CSS = ROOT + 'app/src/v2/css/tokens.css', DOC = ROOT + 'docs/rebuild/design-system.md';
const A = '<!-- tokens:start (generated by app/test/tokens-doc.mjs --write; do not edit by hand) -->', Z = '<!-- tokens:end -->';
const src = fs.readFileSync(CSS, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

// top-level blocks only (a :root inside @media is a layout setting, listed separately)
const blocks = []; { let i = 0, depth = 0, start = 0, sel = '';
  for (; i < src.length; i++) { const c = src[i];
    if (c === '{') { if (depth === 0) { sel = src.slice(start, i).trim(); start = i + 1; } depth++; }
    else if (c === '}') { depth--; if (depth === 0) { blocks.push({sel, body: src.slice(start, i)}); start = i + 1; } } } }
const decls = body => { const o = new Map(); for (const d of body.split(';')) { const m = d.match(/^\s*(--[\w-]+)\s*:\s*([\s\S]+?)\s*$/); if (m) o.set(m[1], m[2].replace(/\s+/g, ' ')); } return o; };
const day = new Map(), night = new Map(), media = [];
for (const b of blocks) {
  if (b.sel === ':root') for (const [k, v] of decls(b.body)) day.set(k, v);
  else if (b.sel === ':root[data-theme="night"]') for (const [k, v] of decls(b.body)) night.set(k, v);
  else if (b.sel.startsWith('@media')) { const inner = b.body.match(/:root\s*\{([^}]*)\}/); if (inner) for (const [k, v] of decls(inner[1])) media.push([b.sel.replace(/\s+/g, ' '), k, v]); } }

// colour maths (WCAG 2 relative luminance), following var() inside the same theme
const resolve = (map, v, n = 0) => { const m = v && v.match(/^var\((--[\w-]+)\)$/); return m && n < 8 ? resolve(map, map.get(m[1]) ?? day.get(m[1]), n + 1) : v; };
const hex = v => { const m = v && v.match(/^#([0-9a-f]{6})$/i); return m ? [0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16)) : null; };
const lum = c => { const [r, g, b] = c.map(x => { x /= 255; return x <= .03928 ? x / 12.92 : ((x + .055) / 1.055) ** 2.4; }); return .2126 * r + .7152 * g + .0722 * b; };
const ratio = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + .05) / (Math.min(x, y) + .05); };
const nightOf = k => night.has(k) ? night.get(k) : day.get(k);
const bgD = hex(resolve(day, day.get('--bg'))), bgN = hex(resolve(new Map([...day, ...night]), nightOf('--bg')));
const cr = (map, k, v, bg) => { const c = hex(resolve(map, v)); return c && bg ? ratio(c, bg).toFixed(2) : ''; };

// families: the first word of the name (--ty-Dragon -> ty), with the core colours kept together
const CORE = new Set(['bg', 'surface', 'wash', 'ink', 'ink-2', 'ink-3', 'rule', 'plot', 'plot-text', 'pick', 'pick-text', 'plate', 'on-plate', 'plate-link']);
const fam0 = k => { const n = k.slice(2); return CORE.has(n) ? 'core' : n.split('-')[0].replace(/\d+$/, ''); };
const keys = [...new Set([...day.keys(), ...night.keys()])];
const size = new Map(); for (const k of keys) size.set(fam0(k), (size.get(fam0(k)) || 0) + 1);
const fam = k => { const f = fam0(k); return f === 'core' || size.get(f) >= 3 ? f : 'other'; }; // families of 1-2 tokens share one table
const groups = new Map(); for (const k of keys) { const f = fam(k); if (!groups.has(f)) groups.set(f, []); groups.get(f).push(k); }
const LABEL = {core: 'Core colours', s: 'Space (--s1 ... --s24, the 4px grid)', t: 'Type sizes (--t13 ... )', d: 'Display sizes', r: 'Corners (--r-*)', other: 'Other'};
const order = ['core', ...[...groups.keys()].filter(f => f !== 'core' && f !== 'other').sort(), ...(groups.has('other') ? ['other'] : [])];
const N = new Map([...day, ...night]);
const cell = v => v == null ? '–' : '`' + v.replace(/\|/g, '\\|') + '`';
let out = [A, '', `Generated from app/src/v2/css/tokens.css: ${keys.length} tokens (${day.size} by day, ${night.size} changed by night). ` +
  'Contrast is the WCAG ratio of a solid colour on that theme\'s page background (--bg), shown only for plain colours; text needs 4.5 (3 for large text and marks).', ''];
for (const f of order) { const ks = groups.get(f);
  out.push(`**${LABEL[f] || '--' + f + '-*'}** (${ks.length})`, '', '| Token | Day | Night | On --bg (day / night) |', '|---|---|---|---|');
  for (const k of ks) { const d = day.get(k), n = night.get(k), a = cr(day, k, d, bgD), b = cr(N, k, nightOf(k), bgN);
    out.push(`| ${k} | ${cell(d)} | ${n == null ? 'same' : cell(n)} | ${a || b ? `${a || '–'} / ${b || '–'}` : ''} |`); }
  out.push(''); }
if (media.length) { out.push('**Set by screen width**', '', '| Width | Token | Value |', '|---|---|---|'); for (const [m, k, v] of media) out.push(`| ${m.replace('@media ', '')} | ${k} | ${cell(v)} |`); out.push(''); }
out.push(Z); const gen = out.join('\n');

const doc = fs.readFileSync(DOC, 'utf8'), i = doc.indexOf(A), j = doc.indexOf(Z);
if (i < 0 || j < 0) { console.log('tokens-doc: markers not found in design-system.md'); process.exit(1); }
const cur = doc.slice(i, j + Z.length);
if (process.argv.includes('--write')) { fs.writeFileSync(DOC, doc.slice(0, i) + gen + doc.slice(j + Z.length)); console.log(`tokens-doc: wrote ${keys.length} tokens`); }
else if (cur !== gen) { console.log('tokens-doc: design-system.md is out of date with tokens.css; run node app/test/tokens-doc.mjs --write'); process.exit(1); }
else console.log(`tokens-doc: up to date (${keys.length} tokens)`);
