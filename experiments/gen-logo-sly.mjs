// The "Sly Devil" logo (Sim, Nov 16): reads the finished SVGs from docs/brand/sly-devil/svg (made by Sim's designer, used as given)
// and writes app/src/data/logo-sly.js, so the site draws the same files. One logo for day and night (its white sticker edge carries
// its own background). Run: node experiments/gen-logo-sly.mjs
import fs from 'fs';
const dir = 'docs/brand/sly-devil/svg/', out = {};
// only the versions the page draws (header, phone header, share images); the icons are their own files
const pick = {full: 'nastyplot-logo', small: 'nastyplot-logo-small', flat: 'nastyplot-logo-flat', smallFlat: 'nastyplot-logo-small-flat', markSmall: 'nastyplot-mark-small'};
// numbers kept to 2 decimals inside the paths (the viewBox is ~950 units for a 220px logo, so 0.005 units is about 0.001px: no visible
// change) to keep the page light; the designer's files in docs/brand/sly-devil stay exactly as delivered
const trim = svg => svg.replace(/(-?\d+\.\d{3,})/g, n => String(+(+n).toFixed(2)));
for (const [k, f] of Object.entries(pick)) out[k] = trim(fs.readFileSync(dir + f + '.svg', 'utf8').trim());
fs.writeFileSync('app/src/data/logo-sly.js', '// The NastyPlot logo "Sly Devil" (Nov 16). Generated by experiments/gen-logo-sly.mjs from docs/brand/sly-devil/svg; do not edit by hand.\nconst NP_LOGO=' + JSON.stringify(out) + ';\n');
console.log('logo-sly.js:', Object.keys(out).join(', '), fs.statSync('app/src/data/logo-sly.js').size, 'bytes');

// the browser-tab and home-screen icons for the new site's head (Nov 16): the designer's favicon.svg, a 32px PNG for browsers without SVG
// icons, and the iPhone home-screen icon; written as app/src/v2/icons.html, which the build puts in the head at <!--NP-ICONS-->
const b64 = f => fs.readFileSync('docs/brand/sly-devil/icons/' + f).toString('base64');
const svgIcon = fs.readFileSync('docs/brand/sly-devil/icons/favicon.svg', 'utf8').trim();
fs.writeFileSync('app/src/v2/icons.html', `<!-- the "Sly Devil" icons (Nov 16), generated by experiments/gen-logo-sly.mjs from docs/brand/sly-devil/icons -->
<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,${encodeURIComponent(svgIcon)}">
<link rel="icon" type="image/png" sizes="32x32" href="data:image/png;base64,${b64('favicon-32.png')}">
<link rel="apple-touch-icon" sizes="180x180" href="data:image/png;base64,${b64('apple-touch-icon.png')}">
`);
console.log('icons.html', fs.statSync('app/src/v2/icons.html').size, 'bytes');
